## CREATING NORMAL CALCULATOR USING PRINT STATEMENT

a = 6
b = 4

print("The Addition for ",a,"+", b, "is: ", a + b)
print("The Subtraction for ",a,"-", b, "is: ", a - b)
print("The Multiplication for ",a,"*", b, "is: ", a * b)
print("The Division(float) for ",a,"/", b, "is: ", a / b)
print("The Division(pure int) for ",a,"//", b, "is: ", a // b)